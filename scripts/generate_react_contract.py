"""Generate browser types and pinned validation rules from Python models."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Annotated, Any, get_args, get_origin

from pydantic import AfterValidator, BaseModel

from zeo_core.cli.intervention_card_types import render_typescript
from zeo_core.cli.schemas import render_schema, rendered_file
from zeo_core.contracts.ui import calendar_views as calendar
from zeo_core.contracts.ui import intervention_cards as cards
from zeo_core.contracts.ui._unicode16 import UNASSIGNED

ROOT = Path(__file__).resolve().parents[1]


def rules(annotation: object, metadata: list[Any]) -> list[str]:
    out = [m.func.__name__ for m in metadata if isinstance(m, AfterValidator)]
    if get_origin(annotation) is Annotated:
        args = get_args(annotation)
        out += rules(args[0], list(args[1:]))
    elif get_args(annotation):
        for arg in get_args(annotation):
            out += rules(arg, [])
    return out


def calendar_contract() -> dict[str, Any]:
    """The calendar_view schema and the field rules of every model it names."""
    schema = render_schema("ui.calendar-view")
    field_rules: dict[str, dict[str, list[str]]] = {}
    for name in [*schema["$defs"], schema["title"]]:
        for module in (calendar, cards):
            model = getattr(module, name, None)
            if isinstance(model, type) and issubclass(model, BaseModel):
                found = {
                    f.alias or key: rules(f.annotation, f.metadata)
                    for key, f in model.model_fields.items()
                    if rules(f.annotation, f.metadata)
                }
                if found:
                    field_rules[name] = found
                break
    return {
        "schema": schema,
        "rules": field_rules,
        "unassigned": UNASSIGNED,
        "refused": cards._REFUSED.pattern,
    }


def artifacts() -> dict[Path, str]:
    schema = render_schema("ui.intervention-card")
    field_rules = {}
    for name, model in vars(cards).items():
        if (
            name in schema["$defs"]
            and isinstance(model, type)
            and issubclass(model, BaseModel)
        ):
            field_rules[name] = {
                f.alias or key: rules(f.annotation, f.metadata)
                for key, f in model.model_fields.items()
                if rules(f.annotation, f.metadata)
            }
    data = {
        "schema": schema,
        "rules": field_rules,
        "unassigned": UNASSIGNED,
        "refused": cards._REFUSED.pattern,
    }
    return {
        ROOT / "contracts/zeocore-v1/ui.intervention-card.schema.json": rendered_file(
            "ui.intervention-card"
        ),
        ROOT / "contracts/zeocore-v1/ui.intervention-card.d.ts": render_typescript(),
        ROOT / "packages/react/src/generated/card.ts": render_typescript(),
        ROOT / "packages/react/src/generated/contract.ts": (
            "// Generated by scripts/generate_react_contract.py; do not edit.\n"
            "export const contract = "
        )
        + json.dumps(data, ensure_ascii=True)
        + ";\n",
        ROOT / "packages/react/src/generated/calendar.ts": render_typescript(
            "ui.calendar-view"
        ),
        ROOT / "packages/react/src/generated/calendar-contract.ts": (
            "// Generated by scripts/generate_react_contract.py; do not edit.\n"
            "export const contract = "
        )
        + json.dumps(calendar_contract(), ensure_ascii=True)
        + ";\n",
    }


if __name__ == "__main__":
    for path, content in artifacts().items():
        path.write_text(content, encoding="utf-8")
